import pytest
from httpx import AsyncClient
import asyncio

@pytest.mark.asyncio
async def test_register_and_login(monkeypatch):
    # import app inside test to avoid import-time side effects during collection
    from app.main import app

    # Use an in-memory replacement for the DB functions to keep tests deterministic
    test_users = {}

    async def fake_find_user_by_email(email: str):
        return test_users.get(email)

    async def fake_create_user(name: str, email: str, password_hash: str):
        user = {"_id": "testid", "name": name, "email": email, "password_hash": password_hash}
        test_users[email] = user
        return user

    monkeypatch.setattr("app.api.auth.find_user_by_email", fake_find_user_by_email)
    monkeypatch.setattr("app.api.auth.create_user", fake_create_user)

    async with AsyncClient(app=app, base_url="http://test") as ac:
        # register
        r = await ac.post("/api/v1/auth/register", json={"name":"Alice","email":"alice@example.com","password":"strongpassword"})
        assert r.status_code == 200
        data = r.json()
        assert data["email"] == "alice@example.com"

        # duplicate registration
        r2 = await ac.post("/api/v1/auth/register", json={"name":"Alice","email":"alice@example.com","password":"strongpassword"})
        assert r2.status_code == 400

        # login
        # monkeypatched create_user stored a hashed password; but security.verify will be used in login route.
        # To keep test simple, monkeypatch find_user_by_email to return a password hash generated by passlib
        from passlib.context import CryptContext
        pwd = CryptContext(schemes=["bcrypt"], deprecated="auto")
        hashed = pwd.hash("strongpassword")
        test_users["alice@example.com"]["password_hash"] = hashed

        r3 = await ac.post("/api/v1/auth/login", json={"email":"alice@example.com","password":"strongpassword"})
        assert r3.status_code == 200
        token_data = r3.json()
        assert "access_token" in token_data
